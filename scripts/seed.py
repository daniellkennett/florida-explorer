# --- hours helpers -----------------------------------------------------------
DAYS = ["mon", "tue", "wed", "thu", "fri", "sat", "sun"]


def hours(**kw):
    """hours(mon=[("09:00","17:00")], ...). Missing day => closed (None)."""
    return {d: kw.get(d) for d in DAYS}


def every(*ranges, closed=()):
    return {d: (None if d in closed else list(ranges)) for d in DAYS}


